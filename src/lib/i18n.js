export function makeT(lang) {
  const table = strings[lang] ?? strings.en;
  return (key, vars = {}) => {
    let s = table[key] ?? strings.en[key] ?? key;
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

export const languages = [
  { code: 'en', label: 'English', locale: 'en-US' },
  { code: 'es', label: 'Español', locale: 'es-US' },
  { code: 'zh', label: '中文', locale: 'zh-CN' },
];

/** BCP-47 locale for Intl formatting in a UI language. */
export const localeFor = (lang) => languages.find((l) => l.code === lang)?.locale ?? 'en-US';

/** Pick the initial language: URL ?lang, stored choice, then the browser's. */
export function detectLanguage(param, stored) {
  const ok = (c) => languages.some((l) => l.code === c);
  if (ok(param)) return param;
  if (ok(stored)) return stored;
  const nav = (typeof navigator !== 'undefined' ? navigator.language : 'en').toLowerCase();
  return languages.find((l) => nav.startsWith(l.code))?.code ?? 'en';
}
